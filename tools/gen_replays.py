#!/usr/bin/env python3
"""
gen_replays.py - Emit per-capture PROGMEM replay tables for the
Replay_*.ino sketches from tools/captures.json.

Each replay runs the whole captured session in ~15 s, so a scale factor
per capture is computed: scale = 15000ms / capture_duration.

Usage: python3 tools/gen_replays.py
"""
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)

TARGET_MS = 15000  # replay duration target

CAPTURES = [
    ("1Whip_1Dodger", "One cube whips Dodger: HELLO handshake, keepalives, two whips, BYE + END."),
    ("1Whip_2Handy", "One cube whips two Handys: three-way keepalive round-robin (slots 0/1/3), two whips."),
    ("1Whip_2Hans", "One cube whips two Hans: dual HELLO, keepalives, a burst of eight whips, BYE + END + UNK9."),
]


def emit(name, desc, rows, out_path):
    t0 = rows[0]["t0"]
    dur_us = rows[-1]["t1"] - t0
    scale_num = TARGET_MS * 1000
    scale_den = dur_us
    # reduce
    g = 1
    a, b = scale_num, scale_den
    while b:
        a, b = b, a % b
    g = a
    scale_num //= g
    scale_den //= g
    L = []
    L.append("// Auto-generated by tools/gen_replays.py from tools/captures.json - DO NOT EDIT.")
    L.append("// Capture: %s  (%d packets over %.0f ms of real time)" % (name, len(rows), dur_us / 1000.0))
    L.append("// %s" % desc)
    L.append("#pragma once")
    L.append("#include <Arduino.h>")
    L.append("")
    L.append("#define OCW_REPLAY_NAME \"%s\"" % name)
    L.append("#define OCW_REPLAY_N %d" % len(rows))
    L.append("#define OCW_REPLAY_SCALE_NUM %d" % scale_num)
    L.append("#define OCW_REPLAY_SCALE_DEN %d" % scale_den)
    L.append("")
    L.append("typedef struct { uint32_t t_us; uint8_t p[7]; } ocw_rep_t;")
    L.append("")
    L.append("static const ocw_rep_t ocw_replay[OCW_REPLAY_N] PROGMEM = {")
    for r in rows:
        p = r["packet"]
        L.append("  {%8d, {%d, %d, %d, %d, %d, %d, %d}},  // t=%dms" %
                 (r["t0"] - t0, p[0], p[1], p[2], p[3], p[4], p[5], p[6],
                  (r["t0"] - t0) // 1000))
    L.append("};")
    with open(out_path, "w") as f:
        f.write("\n".join(L) + "\n")
    print("wrote", out_path, "(scale %d/%d)" % (scale_num, scale_den))


def main():
    data = json.load(open(os.path.join(HERE, "captures.json")))
    for name, desc in CAPTURES:
        rows = data["captures"][name]
        sketch_dir = os.path.join(ROOT, "firmware", "Replay_" + name)
        os.makedirs(sketch_dir, exist_ok=True)
        emit(name, desc, rows, os.path.join(sketch_dir, "replay_data.h"))


if __name__ == "__main__":
    main()
